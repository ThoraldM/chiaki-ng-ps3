#!/usr/bin/env python3
"""Generate ps3/src/font_data.c: antialiased glyph atlases (8-bit alpha) for the menu.

Uses DejaVu Sans (Bitstream Vera license, free to embed). Run from the repo root:
    python3 ps3/tools/gen_font.py /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf \
        /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf > ps3/src/font_data.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
# (name, file index, pixel size)
SIZES = [("small", 0, 20), ("normal", 0, 26), ("bold", 1, 26), ("title", 1, 40)]


def build(font_path, size):
    font = ImageFont.truetype(font_path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    data = bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        advance = round(font.getlength(ch))
        w, h = max(0, right - left), max(0, bottom - top)
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
            data += img.tobytes()
        glyphs.append((offset, w, h, left, top, advance))
    return ascent, descent, glyphs, data


def c_bytes(data):
    out = []
    for i in range(0, len(data), 24):
        out.append("\t" + ",".join("%d" % b for b in data[i:i + 24]) + ",")
    return "\n".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    paths = sys.argv[1:3]
    print("// Generated by ps3/tools/gen_font.py from DejaVu Sans (Bitstream Vera license). Do not edit.")
    print('#include "font.h"\n')
    for name, idx, size in SIZES:
        ascent, descent, glyphs, data = build(paths[idx], size)
        print("static const uint8_t %s_alpha[%d] = {\n%s\n};\n" % (name, max(1, len(data)), c_bytes(data) or "\t0"))
        print("static const FontGlyph %s_glyphs[%d] = {" % (name, len(glyphs)))
        for g in glyphs:
            print("\t{ %d, %d, %d, %d, %d, %d }," % g)
        print("};\n")
        print("const Font font_%s = { %d, %d, %d, %d, %d, %s_glyphs, %s_alpha };\n"
              % (name, size, ascent, descent, FIRST, LAST, name, name))


if __name__ == "__main__":
    main()
